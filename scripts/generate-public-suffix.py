#!/usr/bin/env python3
"""Compile the checked-in PSL snapshot into pure domain data; never downloads during a build."""
import hashlib
from pathlib import Path
import unicodedata

root = Path(__file__).resolve().parent.parent
source = root / 'assets/public-suffix/public_suffix_list.dat'
groups = {'exact': set(), 'wildcard': set(), 'exception': set()}
for raw in source.read_text().splitlines():
    value = raw.strip()
    if not value or value.startswith('//'):
        continue
    kind = 'exception' if value.startswith('!') else 'wildcard' if value.startswith('*.') else 'exact'
    value = value[1:] if kind == 'exception' else value[2:] if kind == 'wildcard' else value
    labels = []
    for label in value.lower().split('.'):
        label = unicodedata.normalize('NFC', label)
        labels.append(label if label.isascii() else 'xn--' + label.encode('punycode').decode())
    groups[kind].add('.'.join(labels))
sha = hashlib.sha256(source.read_bytes()).hexdigest()
text = ('// Generated by scripts/generate-public-suffix.py from the checked-in publicsuffix.org snapshot.\n'
        '// This Source Code Form is subject to the Mozilla Public License, v. 2.0.\n'
        '// See https://mozilla.org/MPL/2.0/ and assets/public-suffix/public_suffix_list.dat.\n'
        f'// Source SHA-256: {sha}\n\nenum PublicSuffixRules {{\n')
for kind, rules in groups.items():
    text += f'    static let {kind}: Set<String> = Set("""\n' + '\n'.join(sorted(rules)) + '\n""".split(separator: "\\n").map(String.init))\n'
text += '}\n'
(root / 'Sources/BrkDomain/PublicSuffixRules.generated.swift').write_text(text)
print(f'Generated {sum(map(len, groups.values()))} rules from {sha}')
